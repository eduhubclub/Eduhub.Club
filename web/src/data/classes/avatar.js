/** Avatar modes students can pick later. Initials are the base default. */
export const AVATAR_TYPES = {
  initials: 'initials',
  emoji: 'emoji',
  upload: 'upload',
  library: 'library',
};

export function getAvatarInitials(studentOrName) {
  const name = typeof studentOrName === 'string' ? studentOrName : studentOrName?.name;
  if (!name) return 'ST';
  return name
    .split(/\s+/)
    .map((n) => n[0])
    .join('')
    .substring(0, 2)
    .toUpperCase();
}

/**
 * Normalize student avatar to a consistent shape.
 * Legacy `emoji` alone maps to emoji type; everything else defaults to initials.
 */
export function normalizeAvatar(student) {
  const avatar = student?.avatar;
  if (avatar?.type && Object.values(AVATAR_TYPES).includes(avatar.type)) {
    return {
      type: avatar.type,
      emoji: avatar.emoji || student?.emoji || '',
      imageUrl: avatar.imageUrl || '',
      libraryId: avatar.libraryId || '',
    };
  }

  if (student?.emoji) {
    return {
      type: AVATAR_TYPES.emoji,
      emoji: student.emoji,
      imageUrl: '',
      libraryId: '',
    };
  }

  return {
    type: AVATAR_TYPES.initials,
    emoji: '',
    imageUrl: '',
    libraryId: '',
  };
}

/** Default avatar payload for new / base users. */
export function createDefaultAvatar() {
  return {
    type: AVATAR_TYPES.initials,
    emoji: '',
    imageUrl: '',
    libraryId: '',
  };
}

export function createEmojiAvatar(emoji) {
  return {
    type: AVATAR_TYPES.emoji,
    emoji,
    imageUrl: '',
    libraryId: '',
  };
}

export function createUploadAvatar(imageUrl) {
  return {
    type: AVATAR_TYPES.upload,
    emoji: '',
    imageUrl,
    libraryId: '',
  };
}

export function createLibraryAvatar(libraryId, imageUrl) {
  return {
    type: AVATAR_TYPES.library,
    emoji: '',
    imageUrl,
    libraryId,
  };
}

/** Simple SVG portrait tiles for the built-in avatar image library. */
function svgAvatar({ id, bg, accent, face }) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 80 80" width="80" height="80">
    <rect width="80" height="80" rx="40" fill="${bg}"/>
    <circle cx="40" cy="34" r="16" fill="${face}"/>
    <ellipse cx="40" cy="62" rx="22" ry="16" fill="${accent}"/>
  </svg>`;
  return {
    id,
    label: id.replace(/^lib-/, '').replace(/-/g, ' '),
    imageUrl: `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`,
  };
}

