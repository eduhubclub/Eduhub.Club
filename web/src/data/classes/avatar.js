function sanitizeCategories(categories) {
  return categories.map((cat) => ({
    ...cat,
    emojis: cat.emojis.filter(
      (item) =>
        item &&
        typeof item === 'object' &&
        typeof item.emoji === 'string' &&
        /\p{Extended_Pictographic}/u.test(item.emoji)
    ),
  }));
}

export const EMOJI_AVATAR_CATEGORIES = sanitizeCategories(RAW_EMOJI_AVATAR_CATEGORIES);
export const EMOJI_LIBRARY = EMOJI_AVATAR_CATEGORIES;

export function getAllEmojiAvatars() {
  return EMOJI_LIBRARY.flatMap((c) => c.emojis.map((item) => item.emoji));
}

export function searchEmojiAvatars(query) {
  const q = (query || '').trim().toLowerCase();
  if (!q) return EMOJI_LIBRARY;

  const terms = q.split(/\s+/).filter(Boolean);
  const exactCategory = EMOJI_LIBRARY.find(
    (cat) => cat.label.toLowerCase() === q || cat.id === q
  );

  if (exactCategory) {
    return [exactCategory];
  }

  const matchesTerm = (item, term) => {
    const words = item.keywords.split(/\s+/);
    return words.some((w) => w === term || w.startsWith(term));
  };

  return EMOJI_LIBRARY.map((cat) => ({
    ...cat,
    emojis: cat.emojis.filter((item) => terms.every((t) => matchesTerm(item, t))),
  })).filter((cat) => cat.emojis.length > 0);
}
